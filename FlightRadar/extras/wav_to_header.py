#!/usr/bin/env python3
"""
wav_to_header.py - convert a WAV file into audio_data.h for the FlightRadar
firmware, so your recorded "military aircraft" announcement gets compiled
into the sketch (no SD card / file upload needed).

Usage:
    python3 wav_to_header.py military.wav

Then copy the audio_data.h it writes into your FlightRadar/ sketch folder,
overwriting the placeholder beep, and re-upload the sketch.

Requirements: just Python 3 (no extra packages).

Recording tips (keeps the file small and matches what the firmware expects):
  - Mono, 16-bit PCM WAV.
  - 16000 Hz sample rate is plenty for a spoken announcement and keeps the
    file small (about 32 KB per second of audio). Most recording apps/sites
    let you choose this, or export at any rate - this script reads whatever
    format the file actually is and the firmware adapts to it, so higher
    rates work too, just use more flash.
  - A few seconds of "Military aircraft" (or whatever line you want) is
    enough - keep it short.
"""
import sys
import wave
import struct
import os

def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    src = sys.argv[1]
    if not os.path.isfile(src):
        print(f"File not found: {src}")
        sys.exit(1)

    with wave.open(src, 'rb') as w:
        channels = w.getnchannels()
        width = w.getsampwidth()
        rate = w.getframerate()
        frames = w.readframes(w.getnframes())

    if width != 2:
        print(f"This file is {width*8}-bit - the firmware needs 16-bit PCM.")
        print("Re-export/convert it as 16-bit PCM WAV (mono or stereo) and try again.")
        sys.exit(1)

    # Build a minimal, correct WAV container around the raw PCM data so the
    # firmware's WAV parser (which just reads the fmt/data chunks) works
    # regardless of what extra chunks your original file had.
    data_len = len(frames)
    byte_rate = rate * channels * width
    block_align = channels * width
    header = b'RIFF' + struct.pack('<I', 36 + data_len) + b'WAVE'
    header += b'fmt ' + struct.pack('<IHHIIHH', 16, 1, channels, rate, byte_rate, block_align, width * 8)
    header += b'data' + struct.pack('<I', data_len)
    wav_bytes = header + frames

    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'audio_data.h')
    out_path = os.path.normpath(out_path)

    with open(out_path, 'w') as f:
        f.write("// audio_data.h - generated by extras/wav_to_header.py from\n")
        f.write(f"// {os.path.basename(src)}\n")
        f.write("// DO NOT hand-edit - regenerate with the script instead.\n")
        f.write("#pragma once\n#include <stdint.h>\n#include <Arduino.h>\n\n")
        f.write(f"// {channels} channel(s), {rate} Hz, 16-bit PCM, {data_len/1000:.1f} KB\n")
        f.write(f"const uint32_t MILITARY_WAV_LEN = {len(wav_bytes)};\n")
        f.write("const uint8_t MILITARY_WAV[] PROGMEM = {\n")
        for i in range(0, len(wav_bytes), 16):
            chunk = wav_bytes[i:i+16]
            f.write("  " + ",".join(f"0x{b:02X}" for b in chunk) + ",\n")
        f.write("};\n")

    kb = len(wav_bytes) / 1024
    print(f"Wrote {out_path}")
    print(f"{channels} channel(s), {rate} Hz, {kb:.1f} KB total.")
    if kb > 500:
        print("That's a fairly large clip to compile in - if the sketch runs low on")
        print("flash space, trim the recording or lower the sample rate.")

if __name__ == '__main__':
    main()
